"""Fallback tables for --ls-remap: count every stack on the LTC + lb position sets (3.1M positions) and route stacks
seen fewer than MIN times to the nearest well-seen stack: same piece band and queen bucket with the fewest and
smallest key changes (half: no pawns -> one half -> both halves; imb3: imbalanced -> balanced first), else the
nearest piece band. usage: make_ls_remap.py <keys, e.g. half:offi or imb3:half:offi> <out file> [MIN]"""
import sys
import numpy as np
keys = sys.argv[1].split(":"); out = sys.argv[2]; MIN = int(sys.argv[3]) if len(sys.argv) > 3 else 50
SIZES = {"imb3": 3, "half": 3, "offi": 2}
DIST = {"imb3": [[0, 1, 1], [1, 0, 2], [1, 2, 0]], "half": [[0, 1, 2], [1, 0, 1], [2, 1, 0]], "offi": [[0, 1], [1, 0]]}
radix = int(np.prod([SIZES[k] for k in keys])); count = 32 * radix
tot = np.zeros(count, np.int64)
for path in ("/var/tmp/claude-ltc/ltcset.npz", "/var/tmp/claude-interp/PE/data/lb.npz"):
    Z = np.load(path)
    g = lambda k: Z["P_" + k].astype(np.int64)
    own_off = g("ownN") + g("ownB") + g("ownR") + g("ownQ"); opp_off = g("oppN") + g("oppB") + g("oppR") + g("oppQ")
    pieces = 2 + own_off + opp_off + g("ownP") + g("oppP")
    base = ((pieces - 1) // 4) * 4 + 2 * (g("ownQ") > 0) + (g("oppQ") > 0)
    pawns = Z["P_ownPbb"].astype(np.uint64) | Z["P_oppPbb"].astype(np.uint64)
    qs = (pawns & np.uint64(0x0F0F0F0F0F0F0F0F)) != 0; ks = (pawns & np.uint64(0xF0F0F0F0F0F0F0F0)) != 0
    d = (g("ownP") - g("oppP")) + 3 * (g("ownN") + g("ownB") - g("oppN") - g("oppB")) + 5 * (g("ownR") - g("oppR")) + 9 * (g("ownQ") - g("oppQ"))
    cls = {"imb3": np.where(np.abs(d) <= 1, 0, np.where(d > 0, 1, 2)), "half": np.where(qs & ks, 0, np.where(qs | ks, 1, 2)),
           "offi": ((own_off >= 2) | (opp_off >= 2)).astype(np.int64)}
    idx = np.zeros(len(base), np.int64)
    for k in keys:
        idx = idx * SIZES[k] + cls[k]
    tot += np.bincount(base * radix + idx, minlength=count)
def split(s):
    b, r = divmod(s, radix); v = []
    for k in reversed(keys):
        r, x = divmod(r, SIZES[k]); v.append(x)
    return b, v[::-1]
good = tot >= MIN
lines = []
for s in range(count):
    if good[s]:
        continue
    b, v = split(s)
    best = None
    for t in np.where(good)[0]:
        bt, vt = split(t)
        band_d = abs(bt // 4 - b // 4) + (0 if bt % 4 == b % 4 else 100)
        key_d = sum(DIST[k][x][y] for k, x, y in zip(keys, v, vt))
        changed = sum(x != y for x, y in zip(v, vt))
        score = (band_d, changed, key_d, -tot[t])
        if best is None or score < best[0]:
            best = (score, t)
    lines.append(f"{s} {best[1]}  # seen {tot[s]}, fallback seen {tot[best[1]]}")
with open(out, "w") as f:
    f.write(f"# --ls-remap table for --ls-keys {':'.join(keys)} ({count} stacks): stacks seen fewer than {MIN} times in 3.1M LTC +\n"
            f"# lb positions -> nearest well-seen stack (same piece band and queen bucket first). Generated by make_ls_remap.py.\n")
    f.write("\n".join(lines) + "\n")
print(f"{':'.join(keys)}: {count} stacks, {int((tot == 0).sum())} never seen, {len(lines)} remapped (seen < {MIN}) -> {out}")
